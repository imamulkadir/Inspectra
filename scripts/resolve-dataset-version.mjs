// Detects the actual on-disk layout of the supplied data/iphone/ folder and
// records which subfolder (if any) holds manifest.json, without ever writing
// into data/iphone/ itself. The supplied dataset may be flat
// (data/iphone/manifest.json) or version-namespaced
// (data/iphone/v1.0.0/manifest.json); this keeps the app from hardcoding a
// version string while still resolving a single concrete DATA_ROOT at
// build/dev time.
//
// Also writes public/sw-cache-version.json — a tiny, gitignored, generated
// file the hand-written public/service-worker.js fetches at install time so
// its cache name can contain both the app version (package.json) and the
// dataset manifest version (section 23.2), without the service worker (a
// plain classic script, not bundled through Vite) needing to import ES
// modules from src/.
import { access, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = path.resolve("data/iphone");
const generatedDir = path.resolve("src/generated");
const generatedFile = path.join(generatedDir, "datasetPath.js");
const publicDir = path.resolve("public");
const swVersionFile = path.join(publicDir, "sw-cache-version.json");
const packageJsonFile = path.resolve("package.json");

async function hasManifest(dir) {
  try {
    await access(path.join(dir, "manifest.json"));
    return true;
  } catch {
    return false;
  }
}

function compareVersionDirs(a, b) {
  const parse = (name) =>
    (name.match(/\d+/g) ?? []).map(Number).concat([0, 0, 0]).slice(0, 3);
  const pa = parse(a);
  const pb = parse(b);
  for (let index = 0; index < 3; index += 1) {
    if (pa[index] !== pb[index]) return pb[index] - pa[index];
  }
  return 0;
}

async function main() {
  if (await hasManifest(root)) {
    await write("");
    return;
  }

  let entries;
  try {
    entries = await readdir(root, { withFileTypes: true });
  } catch {
    throw new Error(
      `Dataset not found. Expected data/iphone/manifest.json or a versioned subfolder such as data/iphone/v1.0.0/manifest.json.`,
    );
  }

  const candidates = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    if (await hasManifest(path.join(root, entry.name))) {
      candidates.push(entry.name);
    }
  }

  if (candidates.length === 0) {
    throw new Error(
      "Dataset not found. No manifest.json in data/iphone/ or any of its immediate subfolders.",
    );
  }

  candidates.sort(compareVersionDirs);
  await write(candidates[0]);
}

async function write(versionDir) {
  await mkdir(generatedDir, { recursive: true });
  const contents = `// AUTO-GENERATED by scripts/resolve-dataset-version.mjs. Do not edit.\nexport const DATASET_VERSION_DIR = ${JSON.stringify(versionDir)};\n`;
  await writeFile(generatedFile, contents, "utf8");
  console.log(
    `Resolved dataset directory: data/iphone/${versionDir || "(root)"}`,
  );

  await writeSwVersionFile(versionDir);
}

async function writeSwVersionFile(versionDir) {
  const manifestPath = path.join(root, versionDir, "manifest.json");
  let datasetVersion = null;
  try {
    const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
    datasetVersion = manifest.version ?? null;
  } catch {
    // dataset manifest unreadable; leave datasetVersion null
  }

  let appVersion = null;
  try {
    const pkg = JSON.parse(await readFile(packageJsonFile, "utf8"));
    appVersion = pkg.version ?? null;
  } catch {
    // package.json unreadable; leave appVersion null
  }

  await mkdir(publicDir, { recursive: true });
  await writeFile(
    swVersionFile,
    `${JSON.stringify({ appVersion, datasetVersion }, null, 2)}\n`,
    "utf8",
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
